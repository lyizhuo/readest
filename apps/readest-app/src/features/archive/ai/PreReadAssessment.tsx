'use client';

import clsx from 'clsx';
import React, { useState } from 'react';

import { useSettingsStore } from '@/store/settingsStore';
import { useTranslation } from '@/hooks/useTranslation';

import { ArchiveBook } from '../types';
import { askAI, AI_DISABLED_HINT, AI_ERROR_HINT, isAIEnabled } from './client';
import { preReadAssessment } from './prompts';

/**
 * 值不值得读 (PRD I): AI pre-read assessment built purely from the archive
 * book's own metadata — no file parsing, safe for paper/audio entries.
 */
const PreReadAssessment: React.FC<{ book: ArchiveBook }> = ({ book }) => {
  const _ = useTranslation();
  const settings = useSettingsStore((state) => state.settings);

  const [answer, setAnswer] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const run = async () => {
    if (!isAIEnabled(settings)) {
      setError(_(AI_DISABLED_HINT));
      return;
    }
    setBusy(true);
    setError(null);
    try {
      setAnswer(
        await askAI(
          settings,
          preReadAssessment({
            title: book.title,
            authors: book.authors,
            publisher: book.publisher,
            publishYear: book.publishYear,
            fictionType: book.fictionType,
            description: book.description,
            rating: book.rating,
          }),
        ),
      );
    } catch (err) {
      console.warn('archive: pre-read assessment failed', err);
      setError(_(AI_ERROR_HINT));
    } finally {
      setBusy(false);
    }
  };

  return (
    <section className='space-y-2 px-4 pt-4'>
      <div className='flex items-center gap-2'>
        <h2 className='text-sm font-semibold text-base-content/70'>{_('Worth reading?')}</h2>
        <button
          className={clsx('btn btn-xs rounded-full', !busy && 'btn-primary')}
          disabled={busy}
          onClick={() => void run()}
        >
          {busy ? _('Thinking…') : answer ? _('Regenerate') : _('Generate assessment')}
        </button>
        {!answer && !busy && !error && (
          <span className='text-[11px] text-base-content/40'>
            {_('AI evaluates this book from its metadata.')}
          </span>
        )}
      </div>
      {error && <p className='text-xs text-error'>{error}</p>}
      {answer && (
        <div className='rounded-xl bg-base-200/60 px-3 py-2 text-sm'>
          <p className='whitespace-pre-wrap'>{answer}</p>
          <p className='mt-1 text-[11px] text-base-content/40'>{_('Generated by AI')}</p>
        </div>
      )}
    </section>
  );
};

export default PreReadAssessment;
